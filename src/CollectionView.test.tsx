import { fireEvent, render, screen, within } from '@testing-library/react'
import '@testing-library/jest-dom/vitest'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { axe } from 'vitest-axe'
import { App } from './App'
import { addCopies, emptyCollection, moveCopies, saveBinder, saveCategory, type CollectionState } from './domain/collection'
import { storageKey } from './domain/storage'

vi.mock('./scanner/camera', () => ({
  requestCamera: vi.fn().mockResolvedValue({ getTracks: () => [] }),
  captureFrame: vi.fn().mockReturnValue({ dataUrl: 'data:image/jpeg;base64,capture', width: 630, height: 880 }),
  getCameraError: vi.fn(), stopCamera: vi.fn(),
}))
const draft = { name: 'Pikachu', set: 'Base', type: 'Pokemon' as const, rarity: 'Rare' as const, quantity: 4, notes: '', elementalTypes: ['Lightning'], generations: ['I'] }
const binder = { id: 'b', name: 'Favorites', color: '#526057', pageCount: 20, rows: 3, columns: 3 }
const initial = () => saveCategory(saveBinder(addCopies(emptyCollection(), draft), binder), 'Trades', 'trades')
function open(state = initial()) {
  localStorage.setItem(storageKey, JSON.stringify(state))
  const result = render(<App />)
  fireEvent.click(screen.getByRole('button', { name: /Open my collection/i }))
  return result
}
const saved = (): CollectionState => JSON.parse(localStorage.getItem(storageKey)!)
const choose = (label: string, value: string) => fireEvent.change(screen.getByLabelText(label, { exact: true }), { target: { value } })
const click = (name: string | RegExp) => fireEvent.click(screen.getByRole('button', { name }))
function selectCopy(number: number) { fireEvent.click(screen.getByLabelText(`Select Pikachu copy ${number}`)) }
function beginMove(numbers: number[]) { numbers.forEach(selectCopy); click(/Move selected/); }

describe('physical collection interface', () => {
  beforeEach(() => { localStorage.clear(); vi.restoreAllMocks() })

  it('creates categories, validates names and preserves them empty; confirms deletion safely', async () => {
    const { container } = open()
    click('+ Add category')
    choose('Category name', ' Unsorted ')
    click('Save category')
    expect(screen.getByRole('alert')).toHaveTextContent(/Unsorted/)
    choose('Category name', 'Treasures')
    click('Save category')
    expect(screen.getByRole('button', { name: 'Treasures' })).toBeTruthy()
    click('Edit category Treasures')
    choose('Category name', 'Treasures renamed')
    click('Save category')
    click('Delete category Trades')
    expect(screen.getByRole('region', { name: 'Confirm deletion' })).toHaveTextContent(/return to Unsorted/)
    expect((await axe(container)).violations).toHaveLength(0)
    click('Cancel deletion')
    expect(saved().categories).toHaveLength(2)
    beginMove([1])
    choose('Destination for copy 1', 'category:trades')
    click('Confirm move')
    click('Delete category Trades')
    click('Confirm deletion')
    expect(saved().copies.every((copy) => copy.location.kind === 'unsorted')).toBe(true)
    expect(saved().copies).toHaveLength(4)
    expect(screen.getByRole('heading', { name: 'Bulk box' })).toHaveFocus()
  })

  it('moves exact copies as a batch, removes/recreates Unsorted and retains focus', () => {
    open()
    click(/^Unsorted/)
    beginMove([1, 2, 3, 4])
    choose('Destination for copy 1', 'binder:b')
    choose('Destination page for copy 1', '2')
    choose('Destination pocket for copy 1', '5')
    for (let i = 2; i <= 4; i++) choose(`Destination for copy ${i}`, 'category:trades')
    click('Confirm move')
    expect(screen.queryByRole('button', { name: /^Unsorted/ })).toBeNull()
    expect(screen.getByRole('heading', { name: 'Bulk box' })).toHaveFocus()
    expect(saved().copies[0].location).toEqual({ kind: 'binder', binderId: 'b', page: 1, pocket: 4 })
    expect(saved().copies).toHaveLength(4)
    choose('Card name', 'Eevee')
    click(/Save card/)
    expect(screen.getByRole('button', { name: /^Unsorted/ })).toBeTruthy()
    expect(saved().copies).toHaveLength(5)
  })

  it('applies scoped filters without hiding nonempty Unsorted and handles invalid ranges', async () => {
    const { container } = open()
    click(/^Unsorted/)
    choose('Search', 'missing')
    click('Apply filters')
    expect(screen.getByText('No cards match those filters')).toBeTruthy()
    expect(screen.getByRole('button', { name: /^Unsorted/ })).toBeTruthy()
    expect((await axe(container)).violations).toHaveLength(0)
    click('Clear filters')
    choose('Minimum value (EUR)', '20')
    choose('Maximum value (EUR)', '2')
    click('Apply filters')
    expect(screen.getByRole('alert')).toHaveTextContent(/Minimum/)
    expect(screen.getAllByLabelText(/Select Pikachu copy/)).toHaveLength(4)
    expect(saved().copies.every((copy) => copy.location.kind === 'unsorted')).toBe(true)
  })

  it('edits independent EUR values, rejects bad values, clears them and filters copies', () => {
    open()
    choose('Value for Pikachu copy 1 (EUR)', '2')
    click('Save value for Pikachu copy 1')
    choose('Value for Pikachu copy 2 (EUR)', '20')
    click('Save value for Pikachu copy 2')
    choose('Value for Pikachu copy 3 (EUR)', '-1')
    click('Save value for Pikachu copy 3')
    expect(screen.getByRole('alert')).toHaveTextContent(/nonnegative/)
    expect(saved().copies[2].valueCents).toBeNull()
    choose('Minimum value (EUR)', '10')
    click('Apply filters')
    expect(screen.getAllByLabelText(/Select Pikachu copy/)).toHaveLength(1)
    expect(screen.getByLabelText('Select Pikachu copy 2')).toBeTruthy()
    click('Clear filters')
    beginMove([2])
    choose('Destination for copy 1', 'category:trades')
    click('Confirm move')
    expect(saved().copies[1].valueCents).toBe(2000)
    choose('Value for Pikachu copy 2 (EUR)', '')
    click('Save value for Pikachu copy 2')
    expect(saved().copies[1].valueCents).toBeNull()
    choose('Value for Pikachu copy 1 (EUR)', '0')
    click('Save value for Pikachu copy 1')
    expect(saved().copies[0].valueCents).toBe(0)
  })

  it('creates/customizes binders and blocks destructive configuration changes', async () => {
    const { container } = open()
    click('+ Create binder')
    expect(screen.getByLabelText('Page count')).toHaveValue(20)
    expect(screen.getByLabelText('Columns per page')).toHaveValue(3)
    click('Save binder')
    expect(screen.getByRole('alert')).toHaveTextContent(/name/)
    choose('Binder name', 'New binder')
    choose('Cover color', '#123456')
    click('Save binder')
    expect(saved().binders).toHaveLength(2)
    click('Edit binder Favorites')
    choose('Page count', '1')
    click('Save binder')
    beginMove([1])
    choose('Destination for copy 1', 'binder:b')
    click('Confirm move')
    click('Edit binder Favorites')
    choose('Columns per page', '4')
    click('Save binder')
    expect(screen.getByRole('alert')).toHaveTextContent(/grid/)
    choose('Columns per page', '3')
    choose('Page count', '2')
    click('Save binder')
    expect(saved().binders.find((item) => item.id === 'b')?.pageCount).toBe(2)
    click('Delete binder Favorites')
    click('Cancel deletion')
    expect(saved().copies[0].location.kind).toBe('binder')
    click('Delete binder Favorites')
    click('Confirm deletion')
    expect(saved().copies[0].location.kind).toBe('unsorted')
    expect((await axe(container)).violations).toHaveLength(0)
  })

  it('preserves gaps, pages and boundary controls and opens exact location links', async () => {
    let state = initial()
    state = moveCopies(state, [{ copyId: state.copies[0].id, location: { kind: 'binder', binderId: 'b', page: 1, pocket: 4 } }])
    const { container } = open(state)
    click('Favorites / Page 2 / Pocket 5')
    expect(screen.getByLabelText('Page number')).toHaveValue(2)
    expect(container.querySelectorAll('[data-pocket]')).toHaveLength(9)
    expect(container.querySelector('[data-pocket="5"]')).toHaveClass('located-pocket')
    expect((await axe(container)).violations).toHaveLength(0)
    beginMove([1])
    click('Confirm move')
    expect(container.querySelector('[data-pocket="5"]')).toHaveTextContent('Empty pocket')
    click('Previous page')
    expect(screen.getByRole('button', { name: 'Previous page' })).toBeDisabled()
    choose('Page number', '20')
    click('Go to page')
    expect(screen.getByRole('button', { name: 'Next page' })).toBeDisabled()
    expect(saved().copies).toHaveLength(4)
    choose('Page number', '21')
    click('Go to page')
    expect(screen.getByRole('alert')).toHaveTextContent(/whole page number/)
  })

  it('rejects occupied and invalid multi-copy moves without partial application', () => {
    open()
    beginMove([1, 2])
    for (let i = 1; i <= 2; i++) choose(`Destination for copy ${i}`, 'binder:b')
    const before = localStorage.getItem(storageKey)
    click('Confirm move')
    expect(screen.getByRole('alert')).toHaveTextContent(/share a pocket/)
    expect(localStorage.getItem(storageKey)).toBe(before)
    choose('Destination pocket for copy 2', '2')
    click('Confirm move')
    expect(saved().copies.filter((copy) => copy.location.kind === 'binder')).toHaveLength(2)
    beginMove([3])
    choose('Destination for copy 1', 'binder:b')
    click('Confirm move')
    expect(screen.getByRole('alert')).toHaveTextContent(/occupied/)
    click('Cancel move')
    expect(saved().copies[2].location.kind).toBe('unsorted')
  })

  it('does not publish failed saves and blocks malformed loads without resetting data', () => {
    open()
    const before = localStorage.getItem(storageKey)
    const spy = vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('Quota exceeded') })
    choose('Card name', 'Eevee')
    click(/Save card/)
    expect(screen.getByRole('alert')).toHaveTextContent(/Could not save/)
    expect(screen.queryByRole('status')).toBeNull()
    expect(screen.getByLabelText('Card name')).toHaveValue('Eevee')
    expect(screen.queryByRole('heading', { name: 'Eevee' })).toBeNull()
    expect(localStorage.getItem(storageKey)).toBe(before)
    spy.mockRestore()
  })

  it('renders a recovery error rather than an editable empty collection', () => {
    localStorage.setItem(storageKey, '{broken')
    render(<App />)
    expect(screen.getByRole('heading', { name: 'Collection needs recovery' })).toBeTruthy()
    expect(screen.queryByLabelText('Card name')).toBeNull()
    expect(localStorage.getItem(storageKey)).toBe('{broken')
    localStorage.setItem(storageKey, JSON.stringify(emptyCollection()))
    click('Retry loading collection')
    expect(screen.getByRole('button', { name: /Open my collection/ })).toBeTruthy()
  })

  it('saves reviewed scanner copies through shared Unsorted intake without camera images', async () => {
    open(emptyCollection())
    click('Scan a card')
    fireEvent.click(await screen.findByRole('button', { name: 'Capture card' }))
    click('Use this capture')
    choose('Card name', 'Pikachu')
    choose('Quantity', '4')
    fireEvent.click(screen.getByLabelText('Lightning'))
    fireEvent.click(screen.getByLabelText('Generation I', { exact: true }))
    click(/Save card/)
    expect(saved().copies).toHaveLength(4)
    expect(saved().entries[0].elementalTypes).toEqual(['Lightning'])
    expect(saved().entries[0].generations).toEqual(['I'])
    expect(saved().copies.every((copy) => copy.location.kind === 'unsorted' && copy.valueCents === null)).toBe(true)
    expect(localStorage.getItem(storageKey)).not.toContain('data:image')
  })

  it('retains the organized collection when generating suggestion previews', () => {
    open()
    const before = localStorage.getItem(storageKey)
    click('Binder ideas')
    click('Favorites')
    click(/Generate layout/)
    expect(screen.getByText(/Preview only/)).toBeTruthy()
    expect(localStorage.getItem(storageKey)).toBe(before)
    expect(within(screen.getByRole('list')).getAllByRole('listitem')).toHaveLength(1)
  })

  it('renders only the active page for a 1,000-copy collection', () => {
    const state = saveBinder(addCopies(emptyCollection(), { ...draft, quantity: 1000 }), binder)
    const { container } = open(state)
    click(/Favorites.*0 \/ 180 pockets/)
    expect(container.querySelectorAll('[data-pocket]')).toHaveLength(9)
    expect(screen.getByText('1000 owned copies · 1 distinct entries')).toBeTruthy()
  })

  it('supports keyboard page navigation, single-page boundaries and an accessible empty state', async () => {
    const user = userEvent.setup()
    const { container } = open(saveBinder(emptyCollection(), { ...binder, pageCount: 1 }))
    expect((await axe(container)).violations).toHaveLength(0)
    expect(screen.queryByRole('button', { name: /^Unsorted/ })).toBeNull()
    click(/Favorites.*0 \/ 9 pockets/)
    expect(screen.getByRole('button', { name: 'Previous page' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Next page' })).toBeDisabled()
    click('Edit binder Favorites')
    choose('Page count', '2')
    click('Save binder')
    const next = screen.getByRole('button', { name: 'Next page' })
    next.focus()
    await user.keyboard('{Enter}')
    expect(screen.getByLabelText('Page number')).toHaveValue(2)
    expect(next).toHaveFocus()
    await user.tab()
    expect(document.activeElement).not.toBe(document.body)
    expect(saved().copies).toEqual([])
  })

  it('shows full-binder guidance and rejects removing a populated trailing page', () => {
    let state = saveBinder(addCopies(emptyCollection(), draft), { ...binder, pageCount: 2, rows: 1, columns: 1 })
    state = moveCopies(state, [
      { copyId: state.copies[0].id, location: { kind: 'binder', binderId: 'b', page: 0, pocket: 0 } },
      { copyId: state.copies[1].id, location: { kind: 'binder', binderId: 'b', page: 1, pocket: 0 } },
    ])
    open(state)
    beginMove([3])
    choose('Destination for copy 1', 'binder:b')
    expect(screen.getByText(/Binder is full/)).toBeTruthy()
    click('Confirm move')
    expect(screen.getByRole('alert')).toHaveTextContent(/free it/)
    expect(saved().binders[0].pageCount).toBe(2)
    click('Cancel move')
    click('Edit binder Favorites')
    choose('Page count', '1')
    click('Save binder')
    expect(screen.getByRole('alert')).toHaveTextContent(/removed pages/)
    expect(saved().binders[0].pageCount).toBe(2)
  })

  it('cancels the scanner without changing organized copies or values', async () => {
    open()
    const before = localStorage.getItem(storageKey)
    click('Scan a card')
    await screen.findByRole('button', { name: 'Capture card' })
    click('Cancel')
    expect(localStorage.getItem(storageKey)).toBe(before)
    expect(screen.getByRole('heading', { name: 'My collection' })).toBeTruthy()
  })

  it('sorts the final unsorted copy using keyboard controls and restores focus', async () => {
    const user = userEvent.setup()
    open(saveCategory(addCopies(emptyCollection(), { ...draft, quantity: 1 }), 'Trades', 'trades'))
    click(/^Unsorted/)
    screen.getByLabelText('Select Pikachu copy 1').focus()
    await user.keyboard(' ')
    screen.getByRole('button', { name: 'Move selected (1)' }).focus()
    await user.keyboard('{Enter}')
    expect(screen.getByLabelText('Destination for copy 1')).toHaveFocus()
    await user.selectOptions(screen.getByLabelText('Destination for copy 1'), 'category:trades')
    await user.tab()
    expect(screen.getByRole('button', { name: 'Confirm move' })).toHaveFocus()
    await user.keyboard('{Enter}')
    expect(screen.queryByRole('button', { name: /^Unsorted/ })).toBeNull()
    expect(screen.getByRole('heading', { name: 'Bulk box' })).toHaveFocus()
    expect(saved().copies[0].location).toEqual({ kind: 'category', categoryId: 'trades' })
  })
})
